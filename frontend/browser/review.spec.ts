import { expect, test, type Page } from './fixtures'
import { seedReview, draftReview as draft, encryption } from './helpers'
const setup = (page: Page, name: string, large = false) => seedReview(page, name, { large })
const first = (page: Page) => page.getByRole('article').filter({ hasText: 'Security · Row 2 ·' })

test('review citations, edit/reapprove, missing evidence and preserved destinations', async ({ page }) => {
  const fixture = await setup(page, 'review-journey'); await draft(page)
  const item = first(page)
  await expect(item.locator('blockquote').filter({ hasText: encryption }).first()).toBeVisible()
  await expect(item.locator('figcaption').filter({ hasText: 'Version review-v1' }).first()).toBeVisible()
  await expect(item.getByText(/Identifier: Q1/)).toBeVisible()
  await expect(item.getByRole('button', { name: 'Approve revision 1', exact: true })).toBeDisabled()
  await page.getByLabel('Reviewer label (unverified)', { exact: true }).fill('Local reviewer')
  await item.getByRole('button', { name: 'Approve revision 1', exact: true }).click()
  await expect(item.getByText('Revision 1 approved.', { exact: true })).toBeVisible()
  await item.getByLabel('Answer text', { exact: true }).fill('Reviewed AES-256 encryption answer.')
  await item.getByLabel('Owner label (optional)', { exact: true }).fill('Security owner')
  await expect(item.getByRole('button', { name: 'Approve revision 1', exact: true })).toBeDisabled()
  await item.getByRole('button', { name: 'Save new revision', exact: true }).click()
  await expect(item.getByText('Revision 2 saved. A new explicit approval is required.', { exact: true })).toBeVisible()
  await expect(item.getByText(/Revision 1 approved by/)).toHaveCount(0)
  await item.getByRole('button', { name: 'Approve revision 2', exact: true }).click()
  await expect(item.getByText('Revision 2 approved.', { exact: true })).toBeVisible()
  const missing = page.getByRole('article').filter({ hasText: 'Is biometric authentication available?' })
  await expect(missing.getByText(/Missing evidence: this draft cannot be approved/)).toBeVisible()
  await expect(missing.getByRole('button', { name: 'Approve revision 1', exact: true })).toBeDisabled()
  await missing.getByLabel('Owner label (optional)', { exact: true }).fill('Evidence owner')
  await missing.getByRole('button', { name: 'Save new revision', exact: true }).click()
  await expect(missing.getByText('Revision 2 saved. A new explicit approval is required.', { exact: true })).toBeVisible()
  await expect(missing.getByRole('button', { name: 'Approve revision 2', exact: true })).toBeDisabled()
  await expect(page.getByRole('article').filter({ hasText: 'What transport encryption is used?' }).getByText(/Preserved destination/)).toBeVisible()
  const items = await (await page.request.get(`/api/questionnaires/${fixture.id}/items`, { headers: fixture.headers })).json()
  const saved = items.items.find((row: { provenance: { row: number; sheet: string } }) => row.provenance.sheet === 'Security' && row.provenance.row === 2)
  expect(saved.current_revision).toBe(2); expect(saved.answer.approval).toBeTruthy(); expect(saved.owner).toBe('Security owner')
  const unanswerable = items.items.find((row: { question: string }) => row.question.includes('biometric'))
  const rejected = await page.request.post(`/api/questionnaire-items/${unanswerable.id}/approve`, { headers: fixture.headers, data: { expected_revision: 2, reviewer: 'Local reviewer' } })
  expect(rejected.status()).toBe(409); expect((await rejected.json()).error.code).toBe('stale_evidence')
})

test('review real revision conflict retains local text and requires explicit comparison before resaving', async ({ page }) => {
  const fixture = await setup(page, 'review-conflict'); await draft(page)
  const item = first(page)
  await item.getByLabel('Answer text', { exact: true }).fill('My unsaved answer')
  const items = await (await page.request.get(`/api/questionnaires/${fixture.id}/items`, { headers: fixture.headers })).json()
  const id = items.items[0].id
  const competing = await page.request.patch(`/api/questionnaire-items/${id}/answer`, { headers: fixture.headers, data: { text: 'Saved by a second reviewer', expected_revision: 1, owner: 'Other owner' } })
  expect(competing.status()).toBe(200)
  await item.getByRole('button', { name: 'Save new revision', exact: true }).click()
  await expect(item.getByRole('alert')).toContainText('revision_conflict')
  await expect(item.getByLabel('Answer text', { exact: true })).toHaveValue('My unsaved answer')
  await item.getByRole('button', { name: 'Reload current item', exact: true }).click()
  await expect(item.getByText('Saved by a second reviewer', { exact: true })).toBeVisible()
  await expect(item.getByLabel('Answer text', { exact: true })).toHaveValue('My unsaved answer')
  await expect(item.getByRole('button', { name: 'Save new revision', exact: true })).toBeDisabled()
  await item.getByRole('button', { name: 'Keep my edits against revision 2', exact: true }).click()
  await item.getByRole('button', { name: 'Save new revision', exact: true }).click()
  await expect(item.getByText('Revision 3 saved. A new explicit approval is required.', { exact: true })).toBeVisible()
  const saved = await (await page.request.get(`/api/questionnaire-items/${id}`, { headers: fixture.headers })).json()
  expect(saved.current_revision).toBe(3); expect(saved.answer.text).toBe('My unsaved answer'); expect(saved.answer.approval).toBeNull()
})

test('review lost approval response requires reload and sends no duplicate approval', async ({ page }) => {
  await setup(page, 'review-uncertain'); await draft(page)
  const item = first(page)
  await page.getByLabel('Reviewer label (unverified)', { exact: true }).fill('Local reviewer')
  let approvalRequests = 0
  page.on('request', request => { if (request.url().endsWith('/approve') && request.method() === 'POST') approvalRequests++ })
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Fetch.enable', { patterns: [{ urlPattern: '*/api/questionnaire-items/*/approve', requestStage: 'Response' }] })
  cdp.on('Fetch.requestPaused', async event => {
    expect(event.responseStatusCode).toBe(200)
    await cdp.send('Fetch.failRequest', { requestId: event.requestId, errorReason: 'Failed' })
    await cdp.send('Fetch.disable')
  })
  await item.getByRole('button', { name: 'Approve revision 1', exact: true }).click()
  await expect(item.getByRole('alert')).toContainText('server may have saved')
  await expect(item.getByRole('button', { name: 'Approve revision 1', exact: true })).toBeDisabled()
  await item.getByRole('button', { name: 'Reload current item', exact: true }).click()
  await expect(item.getByText(/Revision 1 approved by Local reviewer/)).toBeVisible()
  await expect(item.getByRole('button', { name: 'Approve revision 1', exact: true })).toBeDisabled()
  expect(approvalRequests).toBe(1)
  await cdp.detach()
})

test('review bounded batches recover partial progress; pagination and tabs retain unsaved edits', async ({ page }) => {
  const fixture = await setup(page, 'review-pages', true)
  let batches = 0
  await page.route(`**/api/questionnaires/${fixture.id}/draft`, async route => {
    batches++
    expect(route.request().postDataJSON().limit).toBe(25)
    if (batches === 2) await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'temporary_failure', message: 'Synthetic interruption' } }) })
    else await route.continue()
  })
  await page.getByRole('button', { name: 'Draft remaining items', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Drafting can be resumed')
  await expect(page.getByRole('button', { name: 'Draft remaining items', exact: true })).toBeEnabled()
  await draft(page)
  expect(batches).toBe(3)
  const item = page.getByRole('article').filter({ hasText: 'Questions · Row 2 ·' })
  await item.getByLabel('Answer text', { exact: true }).fill('Keep my unsaved text')
  await page.getByRole('button', { name: 'Next items', exact: true }).click()
  await expect(page.getByText('Item page 2 · 45 total', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Previous items', exact: true }).click()
  await expect(item.getByLabel('Answer text', { exact: true })).toHaveValue('Keep my unsaved text')
  await page.getByRole('button', { name: 'Evidence', exact: true }).click()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(item.getByLabel('Answer text', { exact: true })).toHaveValue('Keep my unsaved text')
  const items = await (await page.request.get(`/api/questionnaires/${fixture.id}/items?limit=100`, { headers: fixture.headers })).json()
  expect(items.total).toBe(45)
  expect(items.items.every((row: { current_revision: number; answer: { approval: unknown } }) => row.current_revision === 1 && row.answer.approval === null)).toBe(true)
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  await page.getByRole('button', { name: 'Disconnect and clear key', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Questionnaire review', exact: true })).toHaveCount(0)
})
