import { test, expect, type Page } from './fixtures'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
const tokens = () => JSON.parse(readFileSync(resolve(process.env.EVIDENCEDESK_BROWSER_FIXTURE_DIR!, 'oidc-fixture.json'),'utf8')).tokens as Record<string,string>
const headers = (subject='admin', tenant='enterprise') => ({ Authorization:`Bearer ${tokens()[subject]}`, 'X-Tenant-ID':tenant })
async function login(page:Page,subject='admin') {
  await page.goto('/')
  await expect(page.getByLabel('Access token',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Connect automatically',exact:true})).toHaveCount(0)
  await page.getByLabel('Access token',{exact:true}).fill(tokens()[subject])
  await page.getByRole('button',{name:'Connect workspace'}).click()
  await expect(page.getByText('Your workspace is connected')).toBeVisible()
  await expect(page.getByText(new RegExp(`Verified identity: ${subject}`))).toBeVisible()
}
async function importQuestionnaire(page:Page) {
  const response=await page.request.post('/api/questionnaires',{headers:{...headers(),'Idempotency-Key':crypto.randomUUID()},multipart:{file:{name:'enterprise.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:readFileSync(resolve(import.meta.dirname,'../../samples/security.xlsx'))},mapping:readFileSync(resolve(import.meta.dirname,'../../samples/security.mapping.json'),'utf8')}})
  expect(response.status()).toBe(201)
  return (await response.json()).id as string
}
async function openReview(page:Page) {
  await page.getByRole('button',{name:'Questionnaires',exact:true}).click()
  await page.getByRole('button',{name:'Open enterprise.xlsx',exact:true}).click()
  await page.getByRole('button',{name:'Review answers',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Review enterprise.xlsx',exact:true})).toBeVisible()
}
const first=(page:Page)=>page.getByRole('article').filter({hasText:'Security · Row 2 ·'})

test('enterprise lifecycle: pending approval, immutable update, invalidation, redraft and verified approval',async({page})=>{
  let bootstrapRequests=0
  page.on('request',request=>{if(request.url().includes('/dev/session-key'))bootstrapRequests++})
  await login(page)
  await page.getByRole('button',{name:'Evidence',exact:true}).click()
  for(const [label,value] of [['Evidence title','Enterprise policy'],['Evidence text','Customer data is encrypted at rest using AES-256.'],['Version label','1'],['Evidence expiry','2099-01-01'],['Product','Synthetic product']]) await page.getByLabel(label,{exact:true}).fill(value)
  await page.getByRole('button',{name:'Save immutable evidence version',exact:true}).click()
  await expect(page.getByText(/Immutable version saved as pending/)).toBeVisible()
  await page.getByRole('button',{name:'Approve evidence version',exact:true}).click()
  await expect(page.getByRole('button',{name:'Approve evidence version',exact:true})).toBeDisabled()
  const id=await importQuestionnaire(page)
  await openReview(page)
  await page.getByRole('button',{name:'Draft remaining items',exact:true}).click()
  await expect(page.getByText('Drafting complete. All generated answers still require human review.',{exact:true})).toBeVisible()
  await expect(first(page).locator('blockquote').filter({hasText:'AES-256'})).toBeVisible()
  await expect(page.getByLabel('Reviewer identity (from authentication)',{exact:true})).toHaveValue('admin')
  await expect(page.getByLabel('Reviewer identity (from authentication)',{exact:true})).toBeDisabled()
  await first(page).getByRole('button',{name:'Approve revision 1',exact:true}).click()
  await expect(first(page).getByText('Revision 1 approved.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Evidence',exact:true}).click()
  await page.getByRole('button',{name:'Open evidence Enterprise policy',exact:true}).click()
  for(const [label,value] of [['Evidence text','Customer data is encrypted at rest using AES-128.'],['Version label','2'],['Evidence expiry','2099-01-01']]) await page.getByLabel(label,{exact:true}).fill(value)
  await page.getByRole('button',{name:'Save immutable evidence version',exact:true}).click()
  await expect(page.getByText(/Immutable version saved as pending/)).toBeVisible()
  await page.getByRole('button',{name:'Approve evidence version',exact:true}).click()
  await expect(page.getByRole('button',{name:'Approve evidence version',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Review',exact:true}).click()
  await page.getByRole('button',{name:'Reload review page',exact:true}).click()
  await expect(first(page).getByText(/Evidence access or validity changed/)).toBeVisible()
  await expect(first(page).getByRole('button',{name:'Approve revision 1',exact:true})).toBeDisabled()
  await first(page).getByRole('button',{name:'Redraft from current evidence',exact:true}).click()
  await expect(first(page).locator('blockquote').filter({hasText:'AES-128'})).toBeVisible()
  await first(page).getByRole('button',{name:'Approve revision 2',exact:true}).click()
  await expect(first(page).getByText('Revision 2 approved.',{exact:true})).toBeVisible()
  const saved=await (await page.request.get(`/api/questionnaires/${id}/items`,{headers:headers()})).json()
  expect(saved.items[0].answer.approval.identity_verified).toBe(1)
  expect(saved.items[0].answer.approval.reviewer).toBe('https://issuer.example.invalid|admin')
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download export bundle',exact:true}).click()
  expect(await (await downloadEvent).failure()).toBeNull()
  await expect(page.getByText('1 answers applied · 4 unresolved · 5 total',{exact:true})).toBeVisible()
  expect(bootstrapRequests).toBe(0)
  expect(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length}))).toEqual({local:0,session:0})
})

test('enterprise revoked ACL redacts citations; membership and tenant checks revoke browser access',async({page})=>{
  await login(page)
  const sourceResponse=await page.request.post('/api/evidence',{headers:headers(),data:{title:'Restricted policy',content:'Customer data is encrypted at rest using AES-256.',version:'1',valid_until:'2099-01-01'}})
  expect(sourceResponse.status()).toBe(201)
  const source=await sourceResponse.json()
  expect((await page.request.post(`/api/evidence/${source.id}/approve`,{headers:headers(),data:{version_id:source.current_version}})).status()).toBe(200)
  expect((await page.request.put(`/api/evidence/${source.id}/acl`,{headers:headers(),data:{subject:'reviewer'}})).status()).toBe(200)
  const id=await importQuestionnaire(page)
  expect((await page.request.post(`/api/questionnaires/${id}/draft`,{headers:headers(),data:{limit:25}})).status()).toBe(200)
  await login(page,'reviewer');await openReview(page)
  await expect(first(page).locator('blockquote').filter({hasText:'AES-256'})).toBeVisible()
  await expect(first(page).getByLabel('Answer text',{exact:true})).toBeDisabled()
  await first(page).getByRole('button',{name:'Approve revision 1',exact:true}).click()
  await expect(first(page).getByText('Revision 1 approved.',{exact:true})).toBeVisible()
  expect((await page.request.delete(`/api/evidence/${source.id}/acl`,{headers:headers(),data:{subject:'reviewer'}})).status()).toBe(200)
  await page.getByRole('button',{name:'Reload review page',exact:true}).click()
  await expect(first(page).getByText(/Evidence access or validity changed/)).toBeVisible()
  await expect(first(page).locator('blockquote')).toHaveCount(0)
  await expect(first(page).getByLabel('Answer text',{exact:true})).not.toHaveValue(/AES-256/)
  expect((await page.request.get(`/api/evidence/${source.id}`,{headers:headers('reviewer')})).status()).toBe(404)
  expect((await page.request.get(`/api/questionnaires/${id}`,{headers:headers('other','other-tenant')})).status()).toBe(404)
  expect((await page.request.put('/api/memberships',{headers:headers(),data:{subject:'reviewer',roles:['reviewer'],active:false}})).status()).toBe(200)
  await page.getByRole('button',{name:'Reload review page',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Your workspace is connected',exact:true})).toHaveCount(0)
  await expect(page.getByLabel('Access token',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Questionnaire review',exact:true})).toHaveCount(0)
})
